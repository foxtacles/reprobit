"""Closed schema-v2 source overlays for classic compiler reproductions.

The overlay document is a recipe, not a patch payload.  Every generated byte
is rendered by one of the typed generators below and every edit is addressed
against the immutable clean input by a significant-token context.  Retail
artifacts are neither accepted nor consulted by this module.

This module deliberately consumes in-memory clean inputs.  Filesystem
admission (including symlink and source-manifest checks) belongs to the caller;
the renderer's authority is the exact ``path -> bytes`` mapping it receives.
"""

