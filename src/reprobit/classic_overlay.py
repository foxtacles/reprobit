    class_identifier = _identifier(value.get("class"), f"{context}.class")
    identifier = _identifier(value.get("id"), f"{context}.id")
    initial = _integer(
        value.get("initial"), f"{context}.initial", minimum=-(1 << 31), maximum=(1 << 31) - 1
    )
    increment = _integer(
        value.get("increment"),
        f"{context}.increment",
        minimum=-(1 << 31),
        maximum=(1 << 31) - 1,
    )
